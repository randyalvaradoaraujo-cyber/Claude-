// Une los trozos de un nivel en una sola rejilla de 16 filas.
function construirMapa(def) {
  const ALTO = 16;
  const filas = new Array(ALTO).fill('');
  for (const tr of def.trozos) {
    const ancho = Math.max(...tr.map((f) => f.length));
    const relleno = ALTO - tr.length;
    for (let y = 0; y < ALTO; y++) {
      const f = y < relleno ? '' : tr[y - relleno];
      filas[y] += f.padEnd(ancho, '.');
    }
  }
  return filas;
}

